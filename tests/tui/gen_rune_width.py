#!/usr/bin/env python3
"""Regenerate src/rune_width_table.odin from the `wcwidth` package.

The TUI's cell renderer must agree with the terminal on how many columns a
rune takes, or the diff renderer's cursor model drifts and leaves stale
glyphs behind. Terminals (and pyte, which the TUI tests use) follow the
wcwidth tables (Unicode EastAsianWidth + Emoji_Presentation for width 2,
combining marks / format characters for width 0), so wayu uses the same data.

Usage (needs `pip install wcwidth`, already a pyte dependency):
    python3 tests/tui/gen_rune_width.py > src/rune_width_table.odin
"""

import wcwidth
from wcwidth import wcwidth as width


def ranges(want):
    out, start = [], None
    for cp in range(0xA0, 0x110000):
        w = 1 if 0xD800 <= cp <= 0xDFFF else width(chr(cp))
        if w == want and start is None:
            start = cp
        elif w != want and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def emit(name, comment, rs):
    print(f"// {comment}")
    print(f"@(rodata)\n{name} := [?][2]rune{{")
    line = "\t"
    for a, b in rs:
        item = f"{{0x{a:X}, 0x{b:X}}}, "
        if len(line) + len(item) > 96:
            print(line.rstrip())
            line = "\t"
        line += item
    print(line.rstrip())
    print("}\n")


print("package wayu\n")
print(f"// GENERATED by tests/tui/gen_rune_width.py from wcwidth {wcwidth.__version__}. Do not edit.")
print("// Sorted, non-overlapping inclusive ranges, searched by get_rune_width.\n")
emit("RUNE_WIDTH_ZERO", "Zero columns: combining marks, variation selectors, ZWJ and other format characters.", ranges(0))
emit("RUNE_WIDTH_WIDE", "Two columns: East Asian Wide/Fullwidth and Emoji_Presentation characters.", ranges(2))
